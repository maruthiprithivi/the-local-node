import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { kitContext, loadCourse } from './course.mjs';

export const REPOSITORY = 'https://github.com/maruthiprithivi/the-local-node';
const SITE = 'https://thelocalnode.dev/ai-field-engineer';
const REPO = path.resolve(import.meta.dirname, '../../..');
const TRACK = 'tracks/ai-field-engineer';
const START = '<!-- course-links:start -->';
const END = '<!-- course-links:end -->';

export function codeUrl(kitRel, view = 'tree') {
  if (!/^(03-labs|04-video-source)(\/|$)/.test(kitRel) || kitRel.split('/').some(p => !p || p === '.' || p === '..')) {
    throw new Error('Expected a track-relative public code path');
  }
  return `${REPOSITORY}/${view}/main/${TRACK}/${kitRel.split('/').map(encodeURIComponent).join('/')}`;
}

export function repositoryFiles(model, repo = REPO) {
  const files = new Map();
  const rows = [];
  const lessons = new Map();
  const cell = text => String(text).replace(/\|/g, '\\|').replace(/[\r\n]+/g, ' ');
  for (const day of model.days) {
    for (const step of day.steps) {
      const lesson = step.lesson;
      const label = `Day ${day.n} · Step ${step.n}`;
      rows.push(`| ${day.n}.${step.n} | [${cell(step.title)}](${SITE}${step.route}) | ${lesson ? `[${lesson.dir}](03-labs/lessons/${lesson.dir}/)` : '—'} |`);
      if (lesson) {
        if (!lessons.has(lesson.dir)) lessons.set(lesson.dir, []);
        lessons.get(lesson.dir).push(`[${label}: ${cell(step.title)}](${SITE}${step.route})`);
      }
    }
  }
  files.set(`${TRACK}/COURSE.md`, [
    '# Follow the website course', '',
    '<!-- Generated by website/ai-field-engineer/scripts/repository.mjs from the website course model. -->', '',
    'Follow these steps in order. The website contains the explanation, videos, prerequisites and checks; the linked folders contain the runnable code. Some steps have no separate lab. A shared folder can serve more than one step.', '',
    '[Course home](https://thelocalnode.dev/ai-field-engineer/) · [Local setup](03-labs/README.md)', '',
    '| Order | Website lesson | Code in this repository |', '| --- | --- | --- |', ...rows, '',
    'Regenerate with `node website/ai-field-engineer/scripts/repository.mjs --write` after changing the course. CI checks that this index and the lab backlinks match the website.', '',
  ].join('\n'));
  for (const [dir, links] of lessons) {
    const file = `${TRACK}/03-labs/lessons/${dir}/README.md`;
    const original = fs.readFileSync(path.join(repo, file), 'utf8');
    const block = [START, '> **Follow this lesson on the website:**', ...links.map(l => `> - ${l}`), `>\n> [Full course sequence](${REPOSITORY}/blob/main/${TRACK}/COURSE.md)`, END].join('\n');
    const start = original.indexOf(START), end = original.indexOf(END);
    if ((start < 0) !== (end < 0) || (start >= 0 && (end < start || original.indexOf(START, start + START.length) >= 0 || original.indexOf(END, end + END.length) >= 0))) {
      throw new Error(`Malformed generated backlink block: ${file}`);
    }
    const content = start >= 0
      ? original.slice(0, start).replace(/\n+$/, '\n\n') + original.slice(end + END.length).replace(/^\n+/, '')
      : original;
    const header = content.match(/^# .+\n(?:\n)*(?:>.*\n)*/m);
    if (!header) throw new Error(`Missing lesson heading: ${file}`);
    const at = header.index + header[0].length;
    files.set(file, content.slice(0, at).replace(/\n+$/, '\n\n') + block + '\n\n' + content.slice(at).replace(/^\n+/, ''));
  }
  return files;
}

export function checkRepositoryLinks(model) {
  const stale = [...repositoryFiles(model)].filter(([file, content]) => !fs.existsSync(path.join(REPO, file)) || fs.readFileSync(path.join(REPO, file), 'utf8') !== content).map(([file]) => file);
  if (stale.length) throw new Error(`Repository lesson links are stale; run node website/ai-field-engineer/scripts/repository.mjs --write:\n${stale.join('\n')}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  if (!['--write', '--check'].includes(process.argv[2]) || process.argv.length !== 3) throw new Error('Use --write or --check');
  const model = loadCourse(kitContext(path.join(REPO, TRACK)));
  if (process.argv[2] === '--write') {
    for (const [file, content] of repositoryFiles(model)) fs.writeFileSync(path.join(REPO, file), content);
  } else checkRepositoryLinks(model);
  console.log(`Repository links match ${model.days.length} days, ${model.steps.length} steps and ${new Set(model.steps.flatMap(s => s.lesson ? [s.lesson.dir] : [])).size} lab folders.`);
}
